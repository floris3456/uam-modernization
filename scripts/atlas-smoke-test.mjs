import { appendFile, cp, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { listFiles, loadModel, stableJson, validateModel, rootDir } from './atlas-lib.mjs';
import { stageAtlas } from './generate-atlas.mjs';

async function mustReject(name, mutate) {
  const dir = await mkdtemp(join(tmpdir(), `uam-atlas-${name}-`));
  try {
    const model = await loadModel();
    await mutate(model, dir);
    const path = join(dir, 'atlas.json');
    await writeFile(path, stableJson(model));
    try {
      await validateModel(model, {modelPath: path, rootDir});
    } catch (error) {
      return `${name}: rejected (${error.message.split('\n')[1]?.replace(/^- /, '') ?? error.message})`;
    }
    throw new Error(`${name}: validator incorrectly accepted the mutation.`);
  } finally { await rm(dir, {recursive: true, force: true}); }
}

export async function smokeTest() {
  const results = [];
  results.push(await mustReject('bad dependency', model => { model.gates[1].dependsOn.push('G99'); }));
  results.push(await mustReject('false pass state', model => { model.gates[0].statuses.gate.value = 'passed'; }));
  results.push(await mustReject('broken source link', model => { model.sourceDocuments[0].path = 'docs/does-not-exist.md'; }));
  const staged = await stageAtlas({renderCheck: false});
  const staleDir = await mkdtemp(join(tmpdir(), 'uam-atlas-stale-'));
  try {
    await cp(staged.stageGenerated, staleDir, {recursive: true});
    await appendFile(join(staleDir, 'index.html'), '\n<!-- deliberate stale-output smoke test -->\n');
    let mismatch = false;
    for (const file of await listFiles(staged.stageGenerated)) {
      const expected = await readFile(join(staged.stageGenerated, file));
      const actual = await readFile(join(staleDir, file));
      if (!expected.equals(actual)) { mismatch = true; break; }
    }
    if (!mismatch) throw new Error('stale output: byte comparison incorrectly accepted changed output.');
    results.push('stale output: rejected (generated byte comparison found the deliberate change)');
  } finally {
    await rm(staged.stageRoot, {recursive: true, force: true});
    await rm(staleDir, {recursive: true, force: true});
  }
  return results;
}

if (process.argv[1] === new URL(import.meta.url).pathname) smokeTest().then(results => console.log(results.join('\n'))).catch(error => { console.error(error.message); process.exitCode = 1; });
